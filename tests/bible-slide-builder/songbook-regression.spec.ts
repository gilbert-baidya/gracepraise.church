import { test, expect } from '@playwright/test';
import { mockSongbookSession } from '../fixtures/songbook-session';

test('Songbook retains search, both archives, phonetic reader and chord controls', async ({ page }) => {
  await mockSongbookSession(page);
  await page.goto('/songbook.html');
  await expect(page.locator('#userInfo')).toBeVisible();
  const sidebar = page.locator('#songbookFilterSidebar');
  await sidebar.locator('[data-language="bangla"]').click();
  await expect(page.locator('#songList .song-card').first()).toBeVisible();
  await page.locator('#songList .song-card').first().click();
  await expect(page.locator('#songModal')).toBeVisible();
  const bangla = await page.locator('#songContent').textContent();
  await page.locator('#togglePhonetic').click();
  await expect(page.locator('#togglePhonetic')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('#songContent')).not.toHaveText(bangla || '');
  await page.locator('#toggleChords').click();
  await expect(page.locator('#toggleChords')).toHaveAttribute('aria-pressed', 'false');
  await page.getByRole('button', { name: 'Close song reader' }).click();
  await page.evaluate("showPresentationMode({ title: 'বাংলা গান', lyrics: 'বাংলা গান\\nLatin lyrics\\nC G Am' })");
  await expect(page.locator('#presentationModal')).toHaveAttribute('lang', 'en');
  await expect(page.locator('#presentationContent [lang="bn"]')).toHaveText('বাংলা গান');
  await expect(page.locator('#presentationContent [lang="en"]')).toHaveText(['Latin lyrics', 'C G Am']);
  await page.evaluate('exitPresentation()');
  await sidebar.locator('[data-language="english"]').click();
  await expect(page.locator('#songList .song-card').first()).toBeVisible();
  const title = await page.locator('#songList .song-card .songbook-v18__song-title').first().textContent();
  await page.getByRole('searchbox', { name: 'Search songs' }).fill(title?.trim() || '');
  await expect(page.locator('#songList .song-card').first()).toContainText(title?.trim() || '');
  await page.locator('#songList .song-card').first().click();
  await expect(page.locator('#songContent')).not.toBeEmpty();
});

test('Songbook content keeps its own language independently of the selected site locale', async ({ page }) => {
  await mockSongbookSession(page);
  await page.goto('/songbook.html?lang=bn');
  await expect(page.locator('html')).toHaveAttribute('lang', 'bn');
  await expect(page.locator('main')).toHaveAttribute('lang', 'en');
  const sidebar = page.locator('#songbookFilterSidebar');
  await sidebar.locator('[data-language="bangla"]').click();
  const card = page.locator('#songList .song-card').first();
  await expect(card.locator('h3')).toHaveAttribute('lang', 'bn');
  await expect(card.locator('.add-to-service-btn')).toHaveText('+ Add to Service');
  await expect(page.locator('#alphabetIndex button').first()).toHaveAttribute('lang', 'bn');
  await expect(page.locator('#alphabetSelectionSummary')).toHaveAttribute('lang', 'bn');
  await page.locator('#alphabetIndex button:not([disabled])').nth(1).click();
  await expect(page.locator('#alphabetSelectionSummary [lang="en"]')).toHaveText('songs');
  await page.locator('#alphabetIndex button').first().click();
  await card.locator('.add-to-service-btn').evaluate(button => (button as HTMLButtonElement).click());
  await expect(page.locator('.playlist-title').first()).toHaveAttribute('lang', 'bn');
  await expect(page.locator('.songbook-v18__service-list li span').last()).toHaveAttribute('lang', 'bn');
  await card.click();
  await expect(page.locator('#songModal')).toHaveAttribute('lang', 'en');
  await expect(page.locator('#songTitle')).toHaveAttribute('lang', 'bn');
  await expect(page.locator('#songPhoneticTitle')).toHaveAttribute('lang', 'en');
  await expect(page.locator('#songContent')).toHaveAttribute('lang', 'bn');
  await expect(page.locator('#songContent [lang="bn"]').first()).toBeVisible();
  await page.locator('#togglePhonetic').click();
  await expect(page.locator('#songContent')).toHaveAttribute('lang', 'en');
  await expect(page.locator('#songContent [lang="bn"]')).toHaveCount(0);
  await page.locator('#showBangla').click();
  await expect(page.locator('#songContent')).toHaveAttribute('lang', 'bn');
  await page.getByRole('button', { name: 'Close song reader' }).click();
  await sidebar.locator('[data-language="english"]').click();
  await expect(page.locator('#songList .song-card h3').first()).toHaveAttribute('lang', 'en');
  await expect(page.locator('#alphabetIndex button').first()).toHaveAttribute('lang', 'en');
  await page.locator('#songList .song-card').first().click();
  await expect(page.locator('#songTitle')).toHaveAttribute('lang', 'en');
  await expect(page.locator('#songContent')).toHaveAttribute('lang', 'en');
  expect(await page.evaluate(() => (window as any).songTextLanguage(null))).toBe('en');
});
